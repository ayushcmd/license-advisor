/**
 * Automated Pull Request Generation Engine
 *
 * Authenticates via `@octokit/app` installation tokens, requires explicit opt-in
 * to replace an existing license, creates an isolated feature branch, commits
 * the generated LICENSE file, and opens an explanatory pull request.
 */

import { inspectRootEntries } from '../../public/js/analyzer.js';
import { ServiceError, validatePrRequest } from './licenseService.js';

/**
 * Format a deterministic feature branch name for adding a specific SPDX license.
 *
 * @param {string} licenseId
 * @returns {string}
 */
export function formatLicenseBranchName(licenseId, replaceExisting = false) {
  const slug = String(licenseId)
    .toLowerCase()
    .replace(/[^a-z0-9.-]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `chore/${replaceExisting ? 'replace' : 'add'}-license-${slug}`;
}

/**
 * Build a clear, plain-language Pull Request description summarizing rights and obligations.
 *
 * @param {object} params
 * @returns {string}
 */
export function buildPullRequestBody({ explanation, licensePackage, defaultBranch, existingLicensePath }) {
  const formatBullets = (items, emptyFallback) => {
    if (!items || items.length === 0) return `- ${emptyFallback}`;
    return items.map((item) => `- **${item.label}:** ${item.description}`).join('\n');
  };

  const lines = [
    '## Summary',
    existingLicensePath
      ? `This automated pull request replaces the existing license in \`${existingLicensePath}\` with **${explanation.name} (\`${explanation.id}\`)** targeting \`${defaultBranch}\`. Review the license diff before merging.`
      : `This automated pull request adds a \`${licensePackage.filename}\` file under **${explanation.name} (\`${explanation.id}\`)** targeting \`${defaultBranch}\`.`,
    '',
    explanation.plainSummary,
    '',
    '### Key Policy Highlights',
    `- **Copyleft Obligation:** ${explanation.policyHighlights.copyleftObligation}`,
    `- **Patent Clause:** ${explanation.policyHighlights.patentClause}`,
    `- **Network-Use Trigger:** ${explanation.policyHighlights.networkUseTrigger}`,
    `- **Distribution Rules:** ${explanation.policyHighlights.distributionRequirements}`,
    '',
    '### Permissions',
    formatBullets(explanation.canDo, 'Standard copyright restrictions apply.'),
    '',
    '### Conditions',
    formatBullets(explanation.mustDo, 'No additional conditions.'),
    '',
    '### Limitations',
    formatBullets(explanation.cannotDo, 'No explicit limitations listed.'),
    '',
    '### Reference',
    `- SPDX Specification: ${explanation.sourceUrls.spdx}`,
    `- Official License Text: ${explanation.sourceUrls.official}`,
    '',
    '> *Generated by GitHub License Advisor. This summary is informational and does not constitute formal legal advice.*'
  ];

  return lines.join('\n');
}

async function detectExistingLicenseOnBranch(octokit, { owner, repo, defaultBranch }) {
  const [contentsResult, licenseResult] = await Promise.all([
    octokit.rest.repos.getContent({ owner, repo, path: '', ref: defaultBranch }).catch((err) => {
      if (err?.status === 404) return { data: [] };
      throw err;
    }),
    octokit.rest.licenses.getForRepo({ owner, repo, ref: defaultBranch }).catch((err) => {
      if (err?.status === 404) return null;
      throw err;
    })
  ]);

  const entries = Array.isArray(contentsResult?.data) ? contentsResult.data : [];
  const rootObservations = inspectRootEntries(entries);

  return [...new Set([
    ...rootObservations.licenseFiles.map((file) => file.path),
    ...(licenseResult?.data?.path ? [licenseResult.data.path] : [])
  ])];
}

/**
 * Create a feature branch, commit the customized LICENSE file, and open a Pull Request.
 *
 * @param {object} params
 * @param {string} params.repo
 * @param {string} params.licenseId
 * @param {string|number} [params.year]
 * @param {string} [params.holder]
 * @param {object} params.githubContext
 * @returns {Promise<object>}
 */
export async function createLicensePullRequest({ repo: repoInput, licenseId, year, holder, replaceExisting = false, githubContext }) {
  if (typeof replaceExisting !== 'boolean') {
    throw new ServiceError(400, 'replaceExisting must be a boolean.', 'INVALID_INPUT');
  }
  const validated = validatePrRequest({ repo: repoInput, licenseId, year, holder });
  const { owner, repo, fullName, explanation, licensePackage } = validated;

  if (!githubContext?.isAppConfigured || typeof githubContext.resolveRepoInstallation !== 'function') {
    throw new ServiceError(
      503,
      'GitHub App credentials are not configured on the server. Set GITHUB_APP_ID and private key credentials in .env.',
      'APP_NOT_CONFIGURED'
    );
  }

  let resolution;
  try {
    resolution = await githubContext.resolveRepoInstallation(owner, repo);
  } catch (err) {
    if (err?.status === 401 || err?.status === 403) {
      throw new ServiceError(403, 'GitHub App lacks permission to verify repository installation.', 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Unable to check GitHub App installation: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (!resolution?.installed || !resolution.octokit) {
    throw new ServiceError(
      404,
      `GitHub License Advisor is not installed on "${fullName}". Install the GitHub App on this repository first.`,
      'APP_NOT_INSTALLED'
    );
  }

  const perms = resolution.installation?.permissions || {};
  if (
    (perms.contents && perms.contents !== 'write') ||
    (perms.pull_requests && perms.pull_requests !== 'write')
  ) {
    throw new ServiceError(
      403,
      'GitHub App installation requires Contents (Read & write) and Pull Requests (Read & write) permissions.',
      'INSUFFICIENT_PERMISSIONS'
    );
  }

  const octokit = resolution.octokit;

  let repoData;
  try {
    const res = await octokit.rest.repos.get({ owner, repo });
    repoData = res.data;
  } catch (err) {
    if (err?.status === 403) {
      throw new ServiceError(403, `GitHub App lacks permission to read metadata for "${fullName}".`, 'INSUFFICIENT_PERMISSIONS');
    }
    if (err?.status === 404) {
      throw new ServiceError(404, `Repository "${fullName}" was not found.`, 'NOT_FOUND');
    }
    throw new ServiceError(502, `Failed to load repository details: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (repoData.archived) {
    throw new ServiceError(409, `Repository "${fullName}" is archived and read-only.`, 'REPO_ARCHIVED');
  }

  const defaultBranch = repoData.default_branch || 'main';

  // Resolve base commit SHA of default branch
  let baseSha;
  try {
    const refRes = await octokit.rest.git.getRef({ owner, repo, ref: `heads/${defaultBranch}` });
    baseSha = refRes.data.object.sha;
  } catch (err) {
    if (err?.status === 404 || err?.status === 409) {
      throw new ServiceError(
        409,
        `Default branch "${defaultBranch}" has no initial commits yet. Create an initial commit before opening a license PR.`,
        'EMPTY_REPOSITORY'
      );
    }
    if (err?.status === 403) {
      throw new ServiceError(403, 'GitHub App lacks permission to read Git references.', 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Failed to resolve default branch SHA: ${err.message}`, 'GITHUB_API_ERROR');
  }

  // Replacements require explicit opt-in and an unambiguous existing license.
  let existingLicensePath;
  try {
    const paths = await detectExistingLicenseOnBranch(octokit, { owner, repo, defaultBranch: baseSha });
    if (replaceExisting && paths.length > 1) {
      throw new ServiceError(409, 'Multiple license files found. Resolve which license to replace manually.', 'MULTIPLE_LICENSE_FILES');
    }
    existingLicensePath = paths[0] || null;
  } catch (err) {
    if (err instanceof ServiceError) throw err;
    if (err?.status === 403) {
      throw new ServiceError(403, `GitHub App lacks permission to inspect repository contents for "${fullName}".`, 'INSUFFICIENT_PERMISSIONS');
    }
    throw new ServiceError(502, `Failed to inspect existing repository license files: ${err.message}`, 'GITHUB_API_ERROR');
  }

  if (existingLicensePath && !replaceExisting) {
    throw new ServiceError(
      409,
      `Repository "${fullName}" already contains "${existingLicensePath}" on "${defaultBranch}". Choose "Replace existing license" to propose a replacement PR.`,
      'LICENSE_EXISTS',
      { existingPath: existingLicensePath, defaultBranch }
    );
  }

  if (replaceExisting && !existingLicensePath) {
    throw new ServiceError(409, 'No existing license found. Choose "Add new license" instead.', 'LICENSE_NOT_FOUND');
  }

  let existingFileSha;
  if (replaceExisting) {
    try {
      const { data } = await octokit.rest.repos.getContent({ owner, repo, path: existingLicensePath, ref: baseSha });
      if (data?.type !== 'file' || !data.sha) {
        throw new ServiceError(409, 'The existing license must be a regular file.', 'INVALID_LICENSE_FILE');
      }
      existingFileSha = data.sha;
    } catch (err) {
      if (err instanceof ServiceError) throw err;
      throw new ServiceError(502, `Failed to read existing license: ${err.message}`, 'GITHUB_API_ERROR');
    }
  }
  const action = replaceExisting ? 'replace' : 'add';
  const title = `chore: ${action} ${validated.licenseId} LICENSE`;

  // Create isolated feature branch (never targeting defaultBranch)
  const baseBranchName = formatLicenseBranchName(validated.licenseId, replaceExisting);
  let targetBranch = baseBranchName;

  if (targetBranch === defaultBranch) {
    targetBranch = `${baseBranchName}-file`;
  }

  try {
    await octokit.rest.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${targetBranch}`,
      sha: baseSha
    });
  } catch (err) {
    if (err?.status === 422) {
      const existingPrs = await octokit.rest.pulls
        .list({ owner, repo, state: 'open', head: `${owner}:${targetBranch}` })
        .catch(() => ({ data: [] }));

      if (Array.isArray(existingPrs.data) && existingPrs.data.length > 0) {
        const openPr = existingPrs.data[0];
        throw new ServiceError(
          409,
          `An open license pull request (#${openPr.number}) already exists for branch "${targetBranch}".`,
          'PR_ALREADY_EXISTS',
          { pullNumber: openPr.number, pullUrl: openPr.html_url }
        );
      }

      targetBranch = `${baseBranchName}-${Date.now().toString(36)}`;
      try {
        await octokit.rest.git.createRef({
          owner,
          repo,
          ref: `refs/heads/${targetBranch}`,
          sha: baseSha
        });
      } catch (retryErr) {
        if (retryErr?.status === 403) {
          throw new ServiceError(403, 'GitHub App lacks write permission to create branches.', 'INSUFFICIENT_PERMISSIONS');
        }
        throw new ServiceError(502, `Failed to create feature branch "${targetBranch}": ${retryErr.message}`, 'GITHUB_API_ERROR');
      }
    } else if (err?.status === 403) {
      throw new ServiceError(403, 'GitHub App lacks Contents write permission to create branches.', 'INSUFFICIENT_PERMISSIONS');
    } else {
      throw new ServiceError(502, `Failed to create feature branch "${targetBranch}": ${err.message}`, 'GITHUB_API_ERROR');
    }
  }

  // Commit generated LICENSE onto the dedicated feature branch
  let commitSha = null;
  try {
    const commitRes = await octokit.rest.repos.createOrUpdateFileContents({
      owner,
      repo,
      path: existingLicensePath || licensePackage.filename,
      ...(existingFileSha ? { sha: existingFileSha } : {}),
      message: title,
      content: Buffer.from(licensePackage.content, 'utf8').toString('base64'),
      branch: targetBranch
    });
    commitSha = commitRes.data?.commit?.sha || null;
  } catch (err) {
    if (err?.status === 403 || err?.status === 404) {
      throw new ServiceError(
        403,
        'GitHub App lacks Contents write permission to commit the LICENSE file.',
        'INSUFFICIENT_PERMISSIONS'
      );
    }
    throw new ServiceError(502, `Failed to commit LICENSE file: ${err.message}`, 'GITHUB_API_ERROR');
  }

  // Open Pull Request from feature branch -> default branch
  const body = buildPullRequestBody({ explanation, licensePackage, defaultBranch, existingLicensePath });

  try {
    const prRes = await octokit.rest.pulls.create({
      owner,
      repo,
      title,
      head: targetBranch,
      base: defaultBranch,
      body
    });

    return {
      ok: true,
      repository: fullName,
      licenseId: validated.licenseId,
      branch: targetBranch,
      baseBranch: defaultBranch,
      commitSha,
      pullNumber: prRes.data.number,
      pullUrl: prRes.data.html_url,
      title: prRes.data.title
    };
  } catch (err) {
    if (err?.status === 403 || err?.status === 404) {
      throw new ServiceError(
        403,
        'GitHub App lacks Pull Requests write permission to open the pull request.',
        'INSUFFICIENT_PERMISSIONS'
      );
    }
    if (err?.status === 422) {
      throw new ServiceError(422, `GitHub rejected pull request creation: ${err.message}`, 'PR_VALIDATION_ERROR');
    }
    throw new ServiceError(502, `Failed to open pull request: ${err.message}`, 'GITHUB_API_ERROR');
  }
}

